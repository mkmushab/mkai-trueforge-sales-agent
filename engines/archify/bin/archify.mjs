#!/usr/bin/env node
/**
 * archify — Interactive HTML Architecture & Workflow Diagram Generator
 * Upstream reference: https://github.com/tt-a1i/archify (MIT License)
 * Usage: node engines/archify/bin/archify.mjs --title "System Architecture" --nodes "Client,API Gateway,Worker,DB" --edges "Client->API Gateway,API Gateway->Worker,Worker->DB" --out diagram.html
 */
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const getArg = (flag, fallback = '') => {
  const idx = args.indexOf(flag);
  return idx >= 0 && idx + 1 < args.length ? args[idx + 1] : fallback;
};

if (args.includes('--version') || args.includes('-v')) {
  console.log('archify v1.2.0 (MK-AI Engine Layer)');
  process.exit(0);
}

if (args.includes('--health')) {
  console.log(JSON.stringify({ ok: true, engine: 'tt-a1i/archify', version: '1.2.0', runtime: process.version }));
  process.exit(0);
}

const title = getArg('--title', 'MK-AI Interactive Architecture Diagram');
const nodesRaw = getArg('--nodes', 'User Request,MKGatekeeper (ASK/AUTO/DENY),Department Head,MCP Tool Runtime,Verified Artifact');
const edgesRaw = getArg('--edges', 'User Request->MKGatekeeper (ASK/AUTO/DENY),MKGatekeeper (ASK/AUTO/DENY)->Department Head,Department Head->MCP Tool Runtime,MCP Tool Runtime->Verified Artifact');
const outFile = getArg('--out', path.join(process.cwd(), 'archify-diagram.html'));

const nodes = nodesRaw.split(',').map((s, i) => ({
  id: `node_${i}`,
  label: s.trim(),
  x: 80 + (i % 3) * 290,
  y: 90 + Math.floor(i / 3) * 140,
})).filter((n) => n.label);

const labelToId = new Map(nodes.map((n) => [n.label.toLowerCase(), n.id]));
const edges = edgesRaw.split(',').map((pair) => {
  const [fromStr, toStr] = pair.split('->').map((s) => (s || '').trim());
  return {
    from: labelToId.get(fromStr.toLowerCase()) || nodes[0]?.id || 'node_0',
    to: labelToId.get(toStr.toLowerCase()) || nodes[Math.min(1, nodes.length - 1)]?.id || 'node_0',
    fromLabel: fromStr,
    toLabel: toStr,
  };
}).filter((e) => e.fromLabel && e.toLabel);

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${title.replace(/</g, '&lt;')}</title>
  <style>
    :root { --bg: #0b0f19; --panel: #111827; --border: #1e293b; --emerald: #10b981; --sky: #0ea5e9; --text: #f8fafc; --muted: #94a3b8; }
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body { background: var(--bg); color: var(--text); font-family: 'Inter', -apple-system, BlinkMacSystemFont, sans-serif; padding: 24px; }
    .toolbar { display: flex; justify-content: space-between; align-items: center; padding: 14px 20px; background: var(--panel); border: 1px solid var(--border); border-radius: 12px; margin-bottom: 18px; }
    .toolbar h1 { font-size: 18px; font-weight: 700; color: var(--text); }
    .badge { font-size: 12px; padding: 4px 10px; border-radius: 999px; background: rgba(16,185,129,0.15); color: var(--emerald); border: 1px solid rgba(16,185,129,0.35); }
    .canvas-wrap { position: relative; width: 100%; height: 520px; background: radial-gradient(circle at 20% 20%, rgba(16,185,129,0.08), transparent 40%), #070a12; border: 1px solid var(--border); border-radius: 14px; overflow: hidden; }
    svg.connections { position: absolute; inset: 0; width: 100%; height: 100%; pointer-events: none; }
    .node-card { position: absolute; width: 220px; padding: 14px 16px; background: #131c31; border: 1.5px solid #2dd4bf; border-radius: 12px; cursor: grab; user-select: none; box-shadow: 0 10px 25px rgba(0,0,0,0.45); transition: border-color 0.15s, transform 0.15s; }
    .node-card:hover { border-color: #38bdf8; transform: translateY(-2px); }
    .node-card .idx { font-size: 10px; text-transform: uppercase; letter-spacing: 0.08em; color: var(--emerald); margin-bottom: 4px; font-weight: 700; }
    .node-card .title { font-size: 14px; font-weight: 600; color: var(--text); }
    .legend { margin-top: 14px; font-size: 12px; color: var(--muted); display: flex; justify-content: space-between; }
  </style>
</head>
<body>
  <div class="toolbar">
    <h1>${title.replace(/</g, '&lt;')}</h1>
    <span class="badge">Interactive HTML Diagram (archify) — Drag Nodes to Rearrange</span>
  </div>
  <div class="canvas-wrap" id="canvas">
    <svg class="connections" id="edgesSvg">
      <defs>
        <marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
          <path d="M 0 1 L 10 5 L 0 9 z" fill="#10b981" />
        </marker>
      </defs>
    </svg>
  </div>
  <div class="legend">
    <span>Nodes: ${nodes.length} | Connections: ${edges.length}</span>
    <span>Generated by archify (tt-a1i/archify MIT) inside MK-AI</span>
  </div>
  <script>
    const nodes = ${JSON.stringify(nodes)};
    const edges = ${JSON.stringify(edges)};
    const canvas = document.getElementById('canvas');
    const svg = document.getElementById('edgesSvg');
    const nodeEls = new Map();

    function renderEdges() {
      Array.from(svg.querySelectorAll('line')).forEach(el => el.remove());
      for (const e of edges) {
        const a = nodes.find(n => n.id === e.from);
        const b = nodes.find(n => n.id === e.to);
        if (!a || !b) continue;
        const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
        line.setAttribute('x1', String(a.x + 110));
        line.setAttribute('y1', String(a.y + 34));
        line.setAttribute('x2', String(b.x + 110));
        line.setAttribute('y2', String(b.y + 34));
        line.setAttribute('stroke', '#10b981');
        line.setAttribute('stroke-width', '2');
        line.setAttribute('marker-end', 'url(#arrow)');
        svg.appendChild(line);
      }
    }

    nodes.forEach((n, idx) => {
      const el = document.createElement('div');
      el.className = 'node-card';
      el.style.left = n.x + 'px';
      el.style.top = n.y + 'px';
      el.innerHTML = '<div class="idx">Step ' + (idx + 1) + '</div><div class="title">' + n.label + '</div>';
      let dragging = false, ox = 0, oy = 0;
      el.addEventListener('mousedown', (ev) => { dragging = true; ox = ev.clientX - n.x; oy = ev.clientY - n.y; });
      window.addEventListener('mousemove', (ev) => {
        if (!dragging) return;
        n.x = Math.max(10, ev.clientX - ox);
        n.y = Math.max(10, ev.clientY - oy);
        el.style.left = n.x + 'px';
        el.style.top = n.y + 'px';
        renderEdges();
      });
      window.addEventListener('mouseup', () => { dragging = false; });
      canvas.appendChild(el);
      nodeEls.set(n.id, el);
    });
    renderEdges();
  </script>
</body>
</html>`;

fs.mkdirSync(path.dirname(path.resolve(outFile)), { recursive: true });
fs.writeFileSync(outFile, html, 'utf-8');
console.log(JSON.stringify({
  ok: true,
  engine: 'tt-a1i/archify',
  output_path: path.resolve(outFile),
  nodes_count: nodes.length,
  edges_count: edges.length,
  bytes: Buffer.byteLength(html, 'utf-8'),
}));
