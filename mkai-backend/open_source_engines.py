#!/usr/bin/env python3
"""
MK AI — Hands & Eyes Execution Engines
Wraps open-source execution capabilities under 100% unified MK AI branding:
1. SEO & Website Codebase Engine (audits HTML/Next.js/React code, creates robots.txt & sitemap.xml, fixes meta tags)
2. Local File & Document Processing Engine (OCR/PDF/Docx/Xlsx/Folder Organizer)
3. Video & 9:16 Reel Storyboard + FFmpeg Pipeline Engine
4. Data & SQL Analytics Engine (SQLite / CSV / GST Calculator)
"""
import datetime
import os
import re
from typing import Any, Dict, List


class MKWebsiteSEOEngine:
    """
    Agent #11 (SEO & Discovery) & Agent #2 (Developer) Hands-on Website Engine.
    Audits a customer's website folder, generates robots.txt and sitemap.xml,
    and fixes <title>, <meta name="description">, and OpenGraph tags directly in code.
    """

    @staticmethod
    def audit_and_prepare_fixes(
        project_dir: str,
        site_url: str = "https://example.com",
        brand_name: str = "MK AI Client",
        default_description: str = "Official website powered by MK AI autonomous optimization.",
        apply_changes: bool = False,
    ) -> Dict[str, Any]:
        project_dir = os.path.abspath(project_dir)
        if not os.path.isdir(project_dir):
            return {"success": False, "error": f"Directory not found: {project_dir}"}

        site_url = site_url.rstrip("/")
        public_dir = os.path.join(project_dir, "public") if os.path.isdir(os.path.join(project_dir, "public")) else project_dir

        robots_path = os.path.join(public_dir, "robots.txt")
        sitemap_path = os.path.join(public_dir, "sitemap.xml")

        robots_lines = [
            "# Generated by MK AI SEO & Discovery Agent (#11.3)",
            "User-agent: *",
            "Allow: /",
            "Disallow: /api/",
            "Disallow: /admin/",
            "",
            f"Sitemap: {site_url}/sitemap.xml",
            "",
        ]
        robots_content = "\n".join(robots_lines)

        discovered_routes: List[str] = ["/"]
        html_files: List[str] = []
        for root, dirs, files in os.walk(project_dir):
            dirs[:] = [d for d in dirs if d not in ("node_modules", ".git", "dist", "build", ".next", "release")]
            for fname in files:
                if fname.endswith(".html"):
                    html_files.append(os.path.join(root, fname))
                    if fname != "index.html":
                        discovered_routes.append(f"/{fname.replace('.html', '')}")

        today = datetime.date.today().isoformat()
        url_entries = []
        for route in sorted(set(discovered_routes)):
            prio = "1.0" if route == "/" else "0.8"
            url_entries.append(
                f"  <url>\n    <loc>{site_url}{route}</loc>\n    <lastmod>{today}</lastmod>\n    <changefreq>weekly</changefreq>\n    <priority>{prio}</priority>\n  </url>"
            )
        sitemap_content = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(url_entries)
            + "\n</urlset>\n"
        )

        meta_patches: List[Dict[str, Any]] = []
        for hfile in html_files:
            try:
                with open(hfile, "r", encoding="utf-8") as f:
                    orig = f.read()
            except Exception:
                continue

            updated = orig
            changes: List[str] = []
            if "<title>" not in updated.lower():
                updated = re.sub(
                    r"(<head[^>]*>)",
                    f"\\1\n    <title>{brand_name}</title>",
                    updated,
                    count=1,
                    flags=re.IGNORECASE,
                )
                changes.append("Added missing <title> tag")
            if 'name="description"' not in updated.lower():
                updated = re.sub(
                    r"(<head[^>]*>)",
                    f'\\1\n    <meta name="description" content="{default_description}" />',
                    updated,
                    count=1,
                    flags=re.IGNORECASE,
                )
                changes.append('Added missing <meta name="description"> tag')
            if 'property="og:title"' not in updated.lower():
                updated = re.sub(
                    r"(<head[^>]*>)",
                    f'\\1\n    <meta property="og:title" content="{brand_name}" />\n    <meta property="og:description" content="{default_description}" />',
                    updated,
                    count=1,
                    flags=re.IGNORECASE,
                )
                changes.append("Added OpenGraph meta tags (og:title, og:description)")
            if "application/ld+json" not in updated.lower():
                ld_script = f'<link rel="canonical" href="{site_url}/" />\n    <script type="application/ld+json">{{"@context":"https://schema.org","@type":"Organization","name":"{brand_name}","url":"{site_url}"}}</script>'
                updated = re.sub(
                    r"(<head[^>]*>)",
                    f"\\1\n    {ld_script}",
                    updated,
                    count=1,
                    flags=re.IGNORECASE,
                )
                changes.append("Added canonical link and Schema.org JSON-LD structured data")
            if "<h1" not in updated.lower() and "<body" in updated.lower():
                updated = re.sub(
                    r"(<body[^>]*>)",
                    f"\\1\n  <h1>{brand_name}</h1>",
                    updated,
                    count=1,
                    flags=re.IGNORECASE,
                )
                changes.append("Added missing <h1> primary heading")

            if changes:
                meta_patches.append({
                    "file": hfile,
                    "changes": changes,
                    "applied": False,
                })
                if apply_changes:
                    with open(hfile, "w", encoding="utf-8") as f:
                        f.write(updated)
                    meta_patches[-1]["applied"] = True

        if apply_changes:
            with open(robots_path, "w", encoding="utf-8") as f:
                f.write(robots_content)
            with open(sitemap_path, "w", encoding="utf-8") as f:
                f.write(sitemap_content)

        return {
            "success": True,
            "agent": "11. SEO & Discovery Agent (Sub-Agents 11.2 On-Page SEO & 11.3 Technical SEO Auditor)",
            "project_dir": project_dir,
            "requires_human_approval": not apply_changes,
            "robots_txt": {"path": robots_path, "written": apply_changes, "preview": robots_content},
            "sitemap_xml": {"path": sitemap_path, "written": apply_changes, "routes_count": len(set(discovered_routes)), "preview": sitemap_content},
            "html_meta_patches": meta_patches,
        }


class MKFinanceGSTEngine:
    """Agent #13 (Finance & Accounting — Sub-Agent 13.5 Profit & 13.6 India GST Helper)."""

    @staticmethod
    def calculate_gst_and_margin(
        selling_price: float,
        cogs: float,
        gst_rate_percent: float = 18.0,
        ad_spend_per_order: float = 0.0,
        shipping_cost: float = 0.0,
        is_inclusive: bool = True,
    ) -> Dict[str, Any]:
        if is_inclusive:
            base_price = selling_price / (1.0 + gst_rate_percent / 100.0)
            gst_amount = selling_price - base_price
        else:
            base_price = selling_price
            gst_amount = base_price * (gst_rate_percent / 100.0)

        cgst = gst_amount / 2.0
        sgst = gst_amount / 2.0
        net_profit = base_price - (cogs + ad_spend_per_order + shipping_cost)
        margin_pct = (net_profit / base_price * 100.0) if base_price > 0 else 0.0

        return {
            "selling_price_inr": round(selling_price, 2),
            "taxable_value_inr": round(base_price, 2),
            "gst_rate_percent": gst_rate_percent,
            "total_gst_inr": round(gst_amount, 2),
            "cgst_inr": round(cgst, 2),
            "sgst_inr": round(sgst, 2),
            "net_profit_inr": round(net_profit, 2),
            "net_margin_percent": round(margin_pct, 2),
            "profitable": net_profit > 0,
        }
